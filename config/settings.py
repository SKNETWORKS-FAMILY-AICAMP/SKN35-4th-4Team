# TiDB Cloud 는 TLS 필수. 인증서: TIDB_CA_PATH → 저장소의 isrgrootx1.pem → 없으면 certifi 묶음(ISRG Root X1 포함)
def _tidb_ca():
    for path in (os.getenv("TIDB_CA_PATH"), BASE_DIR / "isrgrootx1.pem"):
        if path and Path(path).exists():
            return path
    import certifi
    return certifi.where()


